// What the build writes beside XenonRecomp's output: a logging stub for each kernel import
// the recompiled code declares and src/runtime/kernel/*.rs does not define (kernel_stubs.rs).

use crate::Result;
use std::collections::BTreeSet;
use std::fs;
use std::path::Path;

fn word(byte: u8) -> bool {
    byte.is_ascii_alphanumeric() || byte == b'_'
}

// An identifier: a letter or _, then letters, digits and _, as long as it goes.
fn identifier(text: &[u8], at: usize) -> Option<&[u8]> {
    if !text.get(at).is_some_and(|&byte| byte.is_ascii_alphabetic() || byte == b'_') {
        return None;
    }
    let length = text[at..].iter().take_while(|&&byte| word(byte)).count();
    Some(&text[at..at + length])
}

fn find_all<'a>(text: &'a [u8], needle: &'a [u8]) -> impl Iterator<Item = usize> + 'a {
    (0..text.len().saturating_sub(needle.len() - 1)).filter(move |&at| text[at..].starts_with(needle))
}

fn name(bytes: &[u8]) -> String {
    String::from_utf8_lossy(bytes).into_owned()
}

fn read(path: &Path) -> Result<Vec<u8>> {
    fs::read(path).map_err(|e| format!("{}: {e}", path.display()))
}

fn write(path: &Path, text: &str) -> Result {
    fs::write(path, text).map_err(|e| format!("{}: {e}", path.display()))
}

// Every import the runtime does not implement logs once and returns 0, so a run
// reports exactly which ones the game reaches. An import counts as implemented once
// some src/runtime/kernel/*.rs defines it with kernel_import!(<name>, ...).
pub fn kernel_stubs(rust: &Path) -> Result {
    // The imports, as the recompiled code declares them: one line each,
    // `fn __imp__<name>(ctx: &mut PPCContext, base: *mut u8);`.
    let library = rust.join("ppc_recomp/src/lib.rs");
    let text = read(&library)?;
    let mut listed = Vec::new();
    for at in find_all(&text, b"fn __imp__") {
        let start = at + b"fn __imp__".len();
        if let Some(found) = identifier(&text, start)
            && text[start + found.len()..].starts_with(b"(ctx: &mut PPCContext, base: *mut u8);")
        {
            listed.push(name(found));
        }
    }
    if listed.is_empty() {
        return Err(format!("{}: no kernel import declared", library.display()));
    }
    let need: BTreeSet<String> = listed.iter().cloned().collect();
    let mut implemented = BTreeSet::new();
    let kernel = Path::new("src/runtime/kernel");
    for file in crate::listing(kernel)? {
        if !file.ends_with(".rs") {
            continue;
        }
        let text = read(&kernel.join(file))?;
        for at in find_all(&text, b"kernel_import!(") {
            let mut start = at + b"kernel_import!(".len();
            start += text[start..].iter().take_while(|byte| byte.is_ascii_whitespace()).count();
            let length = text[start..].iter().take_while(|&&byte| word(byte)).count();
            if length > 0 && text.get(start + length) == Some(&b',') {
                implemented.insert(name(&text[start..start + length]));
            }
        }
    }
    let missing: Vec<&String> = need.difference(&implemented).collect();
    let mut out = String::from(
        "// Generated by cargo xtask (xtask/src/generate.rs) -- do not edit.\n\
         // Every import here logs once and returns 0, so a run reports exactly\n\
         // which ones the game actually reaches (src/runtime/kernel/stubs.rs).\n",
    );
    for name in &missing {
        out += &format!(
            "kernel_import!({name}, |ctx, _memory| {{\n    unimplemented(c\"{name}\");\n    ctx.r3.u64 = 0;\n}});\n"
        );
    }
    // Written only when it changes: the game's build.rs watches it.
    let stubs = rust.join("kernel_stubs.rs");
    if fs::read_to_string(&stubs).ok().as_deref() != Some(out.as_str()) {
        write(&stubs, &out)?;
    }
    println!(
        "kernel imports: {} needed, {} implemented, {} stubbed",
        listed.len(),
        need.intersection(&implemented).count(),
        missing.len()
    );
    let unknown: Vec<&String> = implemented.difference(&need).collect();
    if !unknown.is_empty() {
        let names: Vec<&str> = unknown.iter().map(|name| name.as_str()).collect();
        println!("  note: implemented but not imported by the game: {}", names.join(", "));
    }
    Ok(())
}
