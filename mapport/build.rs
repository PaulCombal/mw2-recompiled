// The PC game's loading rules (zone/defs_pc/: the header, the rules and the rules of each
// asset), embedded by name: a file added there is embedded too. The 360's are the zone
// crate's (zone/defs/).
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn embed(folder: &Path, prefix: &str, table: &mut String) {
    println!("cargo:rerun-if-changed={}", folder.display());
    let mut entries: Vec<_> = fs::read_dir(folder).unwrap().map(|e| e.unwrap().path()).collect();
    entries.sort();
    for path in entries {
        let name = path.file_name().unwrap().to_str().unwrap().to_string();
        if path.is_dir() {
            embed(&path, &format!("{prefix}{name}/"), table);
        } else if name.ends_with(".h") || name.ends_with(".txt") {
            println!("cargo:rerun-if-changed={}", path.display());
            table.push_str(&format!(
                "    ({:?}, include_str!({:?})),\n",
                format!("{prefix}{name}"),
                path.display().to_string()
            ));
        }
    }
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let mut table =
        String::from("// Generated by build.rs from zone/defs_pc/.\npub const PC_DEFINITIONS: &[(&str, &str)] = &[\n");
    embed(&manifest.join("../zone/defs_pc"), "", &mut table);
    table.push_str("];\n");
    fs::write(PathBuf::from(env::var("OUT_DIR").unwrap()).join("pc_definitions.rs"), table).unwrap();
}
